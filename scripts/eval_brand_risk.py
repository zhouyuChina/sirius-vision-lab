#!/usr/bin/env python3
"""Eval brand_risk two-stage pipeline: VLM spot -> watchlist verdict.

Positives: stratified sample of avoid-list case images (known infringement).
Negatives: clean wxw garment photos. Outputs confusion matrix + miss/false lists.
"""
import base64
import difflib
import json
import os
import random
import re
import sys
import time
import urllib.request
import concurrent.futures as cf
from collections import Counter, defaultdict

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
from sirius_vision.templates import TEMPLATES  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "testdata", "avoidlist-images", "manifest.json")
WXW_DIR = os.path.join(ROOT, "testdata", "wxw")
OUT_JSON = os.path.join(ROOT, "testdata", "eval-brand-risk-run2.json")
POS_N = 100
WORKERS = 6

TEMPLATE = TEMPLATES["brand_risk"]

# --- key ---
key = None
with open(os.path.expanduser("~/.hermes/.env")) as f:
    for line in f:
        m = re.match(r"^MINIMAX_CN_API_KEY=(.+)$", line.strip())
        if m:
            key = m.group(1).strip().strip('"').strip("'")
            break
assert key, "MINIMAX_CN_API_KEY not found"

# --- watchlist ---
manifest = json.load(open(MANIFEST))
norm_re = re.compile(r"[^a-z0-9\u4e00-\u9fff]")


def norm(s: str) -> str:
    return norm_re.sub("", s.lower())


WATCH = [(b, norm(b)) for b in sorted({r["brand"] for r in manifest})]

# alias table: norm(alias) -> rights holder brand (generated by gen_aliases.py)
ALIAS_FILE = os.path.join(ROOT, "testdata", "brand-aliases.json")
ALIAS_TO_BRAND: dict[str, str] = {}
if os.path.exists(ALIAS_FILE):
    for brand, aliases in json.load(open(ALIAS_FILE)).items():
        for a in aliases:
            ALIAS_TO_BRAND[norm(a)] = brand
print(f"aliases loaded: {len(ALIAS_TO_BRAND)}")


def match_watch(detected: str):
    d = norm(detected)
    if not d:
        return None
    for orig, n in WATCH:
        if d == n or (len(n) >= 4 and n in d) or (len(d) >= 4 and d in n):
            return orig
    holder = ALIAS_TO_BRAND.get(d)
    if not holder and len(d) >= 5 and ALIAS_TO_BRAND:
        hits = difflib.get_close_matches(d, list(ALIAS_TO_BRAND), n=1, cutoff=0.9)
        holder = ALIAS_TO_BRAND[hits[0]] if hits else None
    return holder


def verdict(parsed: dict) -> str:
    b = parsed.get("brand_or_ip")
    if not b:
        return "pass"
    if match_watch(b):
        return "block"
    # corner seller watermark not on watchlist -> ignore (forge dewatermark handles these)
    if parsed.get("element_position") == "corner_badge" and parsed.get("evidence_type") == "wordmark":
        return "pass"
    return "review"


# --- samples ---
# copyright (image theft) cases are OUT OF SCOPE for brand spotting -> provenance module
COPYRIGHT_TYPES = {"著作权侵权", "著作权", "图片著作权侵权", "款式著作权侵权"}
prov = [r for r in manifest if r["type"] in COPYRIGHT_TYPES]
json.dump(prov, open(os.path.join(ROOT, "testdata", "provenance-positives.json"), "w"),
          ensure_ascii=False, indent=1)
print(f"provenance-module positives parked: {len(prov)}")

random.seed(42)
by_type = defaultdict(list)
for r in manifest:
    if r["type"] not in COPYRIGHT_TYPES:
        by_type[r["type"]].append(r)
positives = []
types = sorted(by_type, key=lambda t: -len(by_type[t]))
quota = POS_N
for i, t in enumerate(types):
    take = round(len(by_type[t]) / sum(len(v) for v in by_type.values()) * POS_N) if i < len(types) - 1 else quota
    take = min(take, quota, len(by_type[t]))
    positives += random.sample(by_type[t], take)
    quota -= take
NEG_DIRS = [WXW_DIR, os.path.join(ROOT, "testdata", "negatives-17zwd")]
negatives = [os.path.join(d, f) for d in NEG_DIRS if os.path.isdir(d)
             for f in sorted(os.listdir(d))
             if f.lower().endswith((".jpg", ".png", ".jpeg")) and f != "manifest.json"]

print(f"positives={len(positives)} negatives={len(negatives)} watchlist={len(WATCH)}")


def ask(fp: str):
    b64 = base64.b64encode(open(fp, "rb").read()).decode()
    full_prompt = TEMPLATE.prompt + "\nSchema: " + json.dumps(TEMPLATE.schema)
    body = json.dumps({
        "model": "MiniMax-M3",
        "messages": [{"role": "user", "content": [
            {"type": "text", "text": full_prompt},
            {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{b64}"}},
        ]}],
        "temperature": 0.1,
    }).encode()
    req = urllib.request.Request(
        "https://api.minimaxi.com/v1/chat/completions", data=body,
        headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=90) as r:
        out = json.loads(r.read())
    return re.sub(r"<think>.*?</think>", "", out["choices"][0]["message"]["content"], flags=re.S).strip()


def repair_json(raw: str, err: str) -> str:
    body = json.dumps({
        "model": "MiniMax-M3",
        "messages": [{"role": "user", "content":
            "Fix this JSON so it strictly validates against the schema. Output ONLY the corrected "
            f"JSON object, no prose.\nSchema: {json.dumps(TEMPLATE.schema)}\nBroken output: {raw}\n"
            f"Validation error: {err}"}],
        "temperature": 0.0,
    }).encode()
    req = urllib.request.Request(
        "https://api.minimaxi.com/v1/chat/completions", data=body,
        headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        out = json.loads(r.read())
    return re.sub(r"<think>.*?</think>", "", out["choices"][0]["message"]["content"], flags=re.S).strip()


def run_one(item):
    label, fp, truth_brand, truth_type = item
    for attempt in (1, 2):
        try:
            raw = ask(fp)
            try:
                parsed = TEMPLATE.parse(raw)
            except ValueError as ve:
                parsed = TEMPLATE.parse(repair_json(raw, str(ve)))
            return {"label": label, "file": os.path.basename(fp), "truth_brand": truth_brand,
                    "truth_type": truth_type, "detected": parsed.get("brand_or_ip"),
                    "evidence": parsed.get("evidence_type"), "position": parsed.get("element_position"),
                    "confidence": parsed.get("confidence"), "note": parsed.get("note"),
                    "verdict": verdict(parsed)}
        except Exception as e:
            if attempt == 2:
                return {"label": label, "file": os.path.basename(fp), "truth_brand": truth_brand,
                        "truth_type": truth_type, "error": f"{type(e).__name__}: {e}", "verdict": "error"}
            time.sleep(2)
    return {"label": label, "file": os.path.basename(fp), "truth_brand": truth_brand,
            "truth_type": truth_type, "error": "unreachable", "verdict": "error"}


tasks = [("pos", os.path.join(ROOT, "testdata", "avoidlist-images", r["file"]), r["brand"], r["type"])
         for r in positives] + \
        [("neg", fp, None, None) for fp in negatives]

t0 = time.time()
with cf.ThreadPoolExecutor(max_workers=WORKERS) as ex:
    results = list(ex.map(run_one, tasks))
print(f"done in {time.time()-t0:.0f}s")

json.dump(results, open(OUT_JSON, "w"), ensure_ascii=False, indent=1)

# --- confusion matrix ---
cm = defaultdict(Counter)
for r in results:
    cm[r["label"]][r["verdict"]] += 1

print("\n=== confusion ===")
print(f"{'':10} {'block':>6} {'review':>7} {'pass':>6} {'error':>6}")
for lab, name in (("pos", "positive"), ("neg", "negative")):
    c = cm[lab]
    print(f"{name:>10} {c['block']:>6} {c['review']:>7} {c['pass']:>6} {c['error']:>6}")

pn, nn = len(positives), len(negatives)
p = cm["pos"]; n = cm["neg"]
intercept = p["block"] + p["review"]
print(f"\npositive: hard-block {p['block']}/{pn} ({p['block']/pn:.0%}), intercept(block+review) {intercept}/{pn} ({intercept/pn:.0%}), MISS {p['pass']}/{pn}")
print(f"negative: pass {n['pass']}/{nn} ({n['pass']/nn:.0%}), review {n['review']}/{nn}, FALSE-BLOCK {n['block']}/{nn}")

print("\n=== misses (pos -> pass/review) ===")
for r in results:
    if r["label"] == "pos" and r["verdict"] in ("pass", "review"):
        print(f"  [{r['verdict']:6}] truth={r['truth_brand']:<28} detected={r.get('detected')!r:<30} ev={r.get('evidence')} pos={r.get('position')}")

print("\n=== false alarms (neg -> block/review) ===")
for r in results:
    if r["label"] == "neg" and r["verdict"] != "pass":
        print(f"  [{r['verdict']:6}] detected={r.get('detected')!r} note={r.get('note')}")

print("\nsaved:", OUT_JSON)
